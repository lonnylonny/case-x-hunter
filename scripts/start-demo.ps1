param([string]$EnvFile = "")

$ErrorActionPreference = "Stop"
# 外部程序失败统一检查退出码，兼容 Windows PowerShell 5.1 与 PowerShell 7。
$PSNativeCommandUseErrorActionPreference = $false
$Root = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot ".."))
if (-not $EnvFile) { $EnvFile = Join-Path $Root ".env" }
$EnvFile = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($EnvFile)
$ComposeArgs = @("compose", "--project-directory", $Root, "--env-file", $EnvFile, "-f", (Join-Path $Root "compose.yaml"))

function Format-Command([string[]]$Arguments) {
    return "docker " + (($Arguments | ForEach-Object { "'" + $_.Replace("'", "''") + "'" }) -join " ")
}

function Fail([string]$Message) {
    [Console]::Error.WriteLine("启动失败：$Message")
    [Console]::Error.WriteLine("诊断命令：" + (Format-Command ($ComposeArgs + @("logs", "--tail", "80", "postgres", "prepare", "api"))))
    [Console]::Error.WriteLine("若端口冲突，修改 CASETRACE_API_PORT 或 CASETRACE_POSTGRES_PORT 后重试。")
    [Console]::Error.WriteLine("若已有数据库卷，请恢复原 CASETRACE_POSTGRES_ADMIN_PASSWORD / CASETRACE_POSTGRES_PASSWORD；修改文件不会轮换库内密码。请保留数据卷。")
    exit 1
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Fail "找不到 Docker；请安装并启动 Docker Desktop，启用 Linux containers 与 Compose。"
}
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { Fail "找不到 Docker Compose 插件；请安装或更新 Docker Compose。" }
& docker info *> $null
if ($LASTEXITCODE -ne 0) { Fail "无法访问 Docker daemon；请启动 Docker Desktop 并检查当前用户权限。" }

function New-Password {
    $Bytes = New-Object byte[] 24
    $Generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $Generator.GetBytes($Bytes) } finally { $Generator.Dispose() }
    return [BitConverter]::ToString($Bytes).Replace("-", "").ToLowerInvariant()
}

if (-not (Test-Path -LiteralPath $EnvFile)) {
    $AdminPassword = New-Password
    do { $AppPassword = New-Password } while ($AppPassword -eq $AdminPassword)
    $Contents = @"
# Generated by scripts/start-demo.ps1. Keep this file private and backed up.
DEEPSEEK_API_KEY=
CASETRACE_POSTGRES_ADMIN_PASSWORD=$AdminPassword
CASETRACE_POSTGRES_PASSWORD=$AppPassword
CASETRACE_POSTGRES_PORT=5432
CASETRACE_API_PORT=8000
"@
    try {
        $Bytes = (New-Object System.Text.UTF8Encoding($false)).GetBytes($Contents + "`n")
        $File = [System.IO.File]::Open($EnvFile, [System.IO.FileMode]::CreateNew)
        try { $File.Write($Bytes, 0, $Bytes.Length) } finally { $File.Dispose() }
    } catch { Fail "无法创建配置文件；请检查目标目录和权限。" }
    Remove-Variable AdminPassword, AppPassword, Contents, Bytes
    Write-Output "已生成本地配置（模型密钥留空）。若使用已有数据库卷，请先恢复原数据库凭据。"
}
if (-not (Test-Path -LiteralPath $EnvFile -PathType Leaf)) { Fail "配置路径不是文件。" }

# 使用 Compose 解析 dotenv、变量插值与宿主覆盖；禁止回显包含凭据的配置。
& docker @ComposeArgs config --quiet *> $null
if ($LASTEXITCODE -ne 0) {
    Fail "Compose 配置无效；请检查 CASETRACE_POSTGRES_ADMIN_PASSWORD、CASETRACE_POSTGRES_PASSWORD 是否缺失或为空，以及端口配置。"
}
$EffectiveEnvironment = & docker @ComposeArgs config --environment 2>$null
if ($LASTEXITCODE -ne 0) { Fail "无法读取 Compose 配置；请更新 Docker Compose（需要 config --environment）。" }
$Settings = @{}
foreach ($Line in $EffectiveEnvironment) {
    if ($Line -match '^(CASETRACE_POSTGRES_ADMIN_PASSWORD|CASETRACE_POSTGRES_PASSWORD|CASETRACE_API_PORT|CASETRACE_POSTGRES_PORT)=(.*)$') {
        $Settings[$Matches[1]] = $Matches[2]
    }
}
Remove-Variable EffectiveEnvironment
foreach ($Key in @("CASETRACE_POSTGRES_ADMIN_PASSWORD", "CASETRACE_POSTGRES_PASSWORD")) {
    $Value = $Settings[$Key]
    if ([string]::IsNullOrWhiteSpace($Value) -or $Value -match 'replace|change_me') {
        Fail "$Key 缺失、为空或仍为占位值；请填入随机密码，已有数据库卷必须使用原密码。"
    }
}
if ($Settings["CASETRACE_POSTGRES_ADMIN_PASSWORD"] -ceq $Settings["CASETRACE_POSTGRES_PASSWORD"]) {
    Fail "CASETRACE_POSTGRES_ADMIN_PASSWORD 与 CASETRACE_POSTGRES_PASSWORD 必须不同。"
}
$ApiPort = "8000"
foreach ($Key in @("CASETRACE_API_PORT", "CASETRACE_POSTGRES_PORT")) {
    $Value = $Settings[$Key]
    if ($Value) {
        if ($Value -notmatch '^[0-9]{1,5}$' -or [int]$Value -lt 1 -or [int]$Value -gt 65535) {
            Fail "CASETRACE_API_PORT / CASETRACE_POSTGRES_PORT 必须是 1–65535 的整数。"
        }
        if ($Key -eq "CASETRACE_API_PORT") { $ApiPort = $Value }
    }
}
Remove-Variable Settings, Value

function Invoke-Step([string[]]$Arguments, [string]$Failure) {
    & docker @ComposeArgs @Arguments
    if ($LASTEXITCODE -ne 0) { Fail $Failure }
}
Invoke-Step -Arguments @("build", "api") -Failure "API 镜像构建失败；检查上方构建错误和网络连接。"
Invoke-Step -Arguments @("up", "-d", "--wait", "postgres") -Failure "PostgreSQL 启动或健康检查失败；检查端口与已有卷凭据。"
Invoke-Step -Arguments @("run", "--rm", "--no-deps", "prepare") -Failure "数据准备失败；检查 prepare 输出和数据库日志，修复后重新运行本入口。"
Invoke-Step -Arguments @("up", "-d", "--wait", "api") -Failure "API 启动或健康检查失败；检查 API 日志和端口。"
Write-Output "启动完成：http://127.0.0.1:$ApiPort"
Write-Output ("停止并保留数据：" + (Format-Command ($ComposeArgs + @("stop"))))
