#!/usr/bin/env bash
# 宿主只需 Bash 与 Docker Compose；不执行 .env 中的 shell 文本。
set -euo pipefail

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
if (( $# > 1 )); then
    printf '用法：bash scripts/start-demo.sh [ENV_FILE]\n' >&2
    exit 1
fi
ENV_FILE=${1:-"$ROOT/.env"}
if [[ "$ENV_FILE" != /* ]]; then ENV_FILE="$PWD/$ENV_FILE"; fi
COMPOSE=(docker compose --project-directory "$ROOT" --env-file "$ENV_FILE" -f "$ROOT/compose.yaml")

fail() {
    printf '启动失败：%s\n' "$1" >&2
    printf '诊断命令：' >&2
    printf '%q ' "${COMPOSE[@]}" logs --tail 80 postgres prepare api >&2
    printf '\n若端口冲突，修改 CASETRACE_API_PORT 或 CASETRACE_POSTGRES_PORT 后重试。\n' >&2
    printf '若已有数据库卷，请恢复原 CASETRACE_POSTGRES_ADMIN_PASSWORD / CASETRACE_POSTGRES_PASSWORD；修改文件不会轮换库内密码。请保留数据卷。\n' >&2
    exit 1
}

command -v docker >/dev/null 2>&1 || fail '找不到 Docker；请安装 Docker Engine/Desktop 并启用 Compose。'
docker compose version >/dev/null 2>&1 || fail '找不到 Docker Compose 插件；请安装或更新 Docker Compose。'
docker info >/dev/null 2>&1 || fail '无法访问 Docker daemon；请启动 Docker Engine/Desktop 并检查当前用户权限。'

if [[ ! -e "$ENV_FILE" ]]; then
    admin_password=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')
    app_password=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')
    while [[ "$app_password" == "$admin_password" ]]; do
        app_password=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')
    done
    if ! (umask 077; set -o noclobber; cat > "$ENV_FILE" <<EOF
# Generated by scripts/start-demo.sh. Keep this file private and backed up.
DEEPSEEK_API_KEY=
CASETRACE_POSTGRES_ADMIN_PASSWORD=$admin_password
CASETRACE_POSTGRES_PASSWORD=$app_password
CASETRACE_POSTGRES_PORT=5432
CASETRACE_API_PORT=8000
EOF
    ); then
        fail '无法创建配置文件；请检查目标目录和权限。'
    fi
    unset admin_password app_password
    printf '已生成本地配置（模型密钥留空）。若使用已有数据库卷，请先恢复原数据库凭据。\n'
fi
[[ -f "$ENV_FILE" ]] || fail '配置路径不是文件。'

# 只捕获 Compose 解析结果，避免另写 dotenv 解析器；不回显包含凭据的配置。
"${COMPOSE[@]}" config --quiet >/dev/null 2>&1 || fail 'Compose 配置无效；请检查 CASETRACE_POSTGRES_ADMIN_PASSWORD、CASETRACE_POSTGRES_PASSWORD 是否缺失或为空，以及端口配置。'
effective_env=$("${COMPOSE[@]}" config --environment 2>/dev/null) || fail '无法读取 Compose 配置；请更新 Docker Compose（需要 config --environment）。'
admin_password=''
app_password=''
api_port=8000
postgres_port=5432
while IFS='=' read -r key value; do
    case "$key" in
        CASETRACE_POSTGRES_ADMIN_PASSWORD) admin_password=$value ;;
        CASETRACE_POSTGRES_PASSWORD) app_password=$value ;;
        CASETRACE_API_PORT) api_port=${value:-8000} ;;
        CASETRACE_POSTGRES_PORT) postgres_port=${value:-5432} ;;
    esac
done <<< "$effective_env"
unset effective_env
for key in CASETRACE_POSTGRES_ADMIN_PASSWORD CASETRACE_POSTGRES_PASSWORD; do
    if [[ "$key" == CASETRACE_POSTGRES_ADMIN_PASSWORD ]]; then value=$admin_password; else value=$app_password; fi
    case "$value" in
        ''|*[Rr][Ee][Pp][Ll][Aa][Cc][Ee]*|*[Cc][Hh][Aa][Nn][Gg][Ee]_[Mm][Ee]*)
            fail "$key 缺失、为空或仍为占位值；请填入随机密码，已有数据库卷必须使用原密码。" ;;
    esac
done
[[ "$admin_password" != "$app_password" ]] || fail 'CASETRACE_POSTGRES_ADMIN_PASSWORD 与 CASETRACE_POSTGRES_PASSWORD 必须不同。'
unset admin_password app_password value
for key in api_port postgres_port; do
    if [[ "$key" == api_port ]]; then value=$api_port; else value=$postgres_port; fi
    [[ "$value" =~ ^[0-9]{1,5}$ ]] && (( 10#$value >= 1 && 10#$value <= 65535 )) || fail 'CASETRACE_API_PORT / CASETRACE_POSTGRES_PORT 必须是 1–65535 的整数。'
done
unset value

"${COMPOSE[@]}" build api || fail 'API 镜像构建失败；检查上方构建错误和网络连接。'
"${COMPOSE[@]}" up -d --wait postgres || fail 'PostgreSQL 启动或健康检查失败；检查端口与已有卷凭据。'
"${COMPOSE[@]}" run --rm --no-deps prepare || fail '数据准备失败；检查 prepare 输出和数据库日志，修复后重新运行本入口。'
"${COMPOSE[@]}" up -d --wait api || fail 'API 启动或健康检查失败；检查 API 日志和端口。'
printf '启动完成：http://127.0.0.1:%s\n' "$api_port"
printf '停止并保留数据：'
printf '%q ' "${COMPOSE[@]}" stop
printf '\n'
